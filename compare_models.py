#!/usr/bin/env python3
"""
Benchmark comparison of SPX IV surface forecasting models.

Scope: the tuned models for the c63/h21/precovid/level task —
DLinear, HOT (kronecker_product + kronecker_sum), DynGWN, PatchTST
(patch3 + patch7) — plus a built-in persistence baseline. Each HOT and
PatchTST variant is reported as its own row.

For every model the result dir is resolved by reading its tuning
leaderboard and picking the combo with the lowest `best_val_loss` that
has both `config.json` and `best_model.pt` on disk.

Once a directory is chosen, if `pred.npy` is present it is loaded as-is.
Otherwise it is regenerated by running
    `<regen_script> --predict_only --out_dir <dir> --batch_size <INFER_BATCH>`
which reads config.json + best_model.pt and writes pred.npy alongside.
The default INFER_BATCH is 32 — this matches local capacity, regardless of
the (typically larger) batch size used during Colab training.

All model scripts denormalize predictions to ORIGINAL target-space units
(raw IV for level; raw log-diff for logdiff) before saving pred.npy. The
reference trues built here live in the same space, so all metrics below are
in original target-space units (vol-points for level).

Each model's start_dates.npy aligns its windows to the reference test set;
mismatched window counts surface as a loud date-alignment failure.

Persistence baseline: built fresh from the CSV inside `build_reference()`
(`Persist(ref)` row in the table). Not a separate model entry.

Per-model side-effect: `metrics_test.json` is written into each model's
result dir alongside pred.npy, so a single model's scores can be inspected
without rebuilding the whole table.

Metrics (all in original target-space units):
  mse, rmse, mae, rse  standard regression metrics
  bias                 mean signed error; positive = over-prediction
  da                   directional accuracy: fraction where sign(pred)==sign(true)
  ic_mean, ic_std      Spearman rank-IC across (window, step) over N_IV features.
                       target_space=level   : computed on (pred-origin) vs (true-origin),
                                              i.e. ranks cells by forecast change. Persist(ref)
                                              → ic = NaN by construction.
                       target_space=logdiff : computed on raw pred vs true (logdiffs are
                                              already changes), i.e. ranks cells by today's
                                              log-return. Persist(ref) gives a real number.

LSTS components (from lsts_loss.py — surface-shape losses on the IV grid):
  lsts_level          MSE of surface-mean (overall level offset)
  lsts_skew           MSE of moneyness slope (smile shape)
  lsts_term           MSE of tau slope (term-structure shape)
  lsts_curvature      MSE of moneyness 2nd difference (curvature)

Outputs saved to --out_dir (default: comparison_results/):
  {dataset}_{ts}_*.csv             timestamped overall metrics
  latest_{tag}.csv                 always overwritten with most recent run
  latest_horizons_{tag}.csv        per-horizon ic / mse / mae / lsts_* per model
  latest_summary_{tag}.json        machine-readable summary
"""

