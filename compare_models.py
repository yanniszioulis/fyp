# ─── Date alignment ───────────────────────────────────────────────────────────

def align_to_ref(pred: np.ndarray, pred_dates: np.ndarray,
                 ref_dates: np.ndarray, name: str) -> np.ndarray:
    pred_dates = pred_dates.astype("datetime64[D]")
    date_to_idx = {d: i for i, d in enumerate(pred_dates)}
    indices, missing = [], []
    for d in ref_dates:
        i = date_to_idx.get(d)
        if i is None:
            missing.append(str(d))
        else:
            indices.append(i)
    if missing:
        raise ValueError(
            f"{name}: {len(missing)}/{len(ref_dates)} reference dates not in pred "
            f"(first missing: {missing[0]})"
        )
    return pred[np.array(indices)]


# ─── Metrics ──────────────────────────────────────────────────────────────────

def _lsts_components(pred: np.ndarray, true: np.ndarray,
                     moneyness: np.ndarray, tau: np.ndarray) -> dict:
    """LSTS components computed on a (..., n_tau, n_k) reshape of the flat
    n_iv-column predictions. Inputs are float32 numpy of shape [B, n_iv]
    (B can be N*P, or just N for a single horizon)."""
    n_m, n_t = len(moneyness), len(tau)
    pred_g = pred.reshape(-1, n_t, n_m)
    true_g = true.reshape(-1, n_t, n_m)
    p_t = torch.from_numpy(pred_g)
    t_t = torch.from_numpy(true_g)
    k_t = torch.from_numpy(moneyness)
    tau_t = torch.from_numpy(tau)
    comps = compute_lsts_components(p_t, t_t, k_t, tau_t)
    return {f"lsts_{k}": float(v.detach().cpu()) for k, v in comps.items()}


def compute_metrics(pred: np.ndarray, true: np.ndarray,
                    moneyness: np.ndarray, tau: np.ndarray,
                    origin: np.ndarray, target_space: str) -> dict:
    """
    pred, true, origin: [N, pred_len, n_iv] in original target-space units.
    `origin` is the forecast origin (last input value, broadcast across the
    horizon) — used to convert level predictions to changes for IC.
    `target_space` decides what IC ranks: 'level' subtracts origin (so IC ranks
    cells by forecast change in IV); 'logdiff' uses raw values (logdiffs are
    already changes, so the raw rank IS the cross-sectional direction signal).
    Returns scalar metrics plus per-horizon arrays (keyed with '_' prefix).
    """
    diff  = pred - true
    sq    = diff * diff
    abs_d = np.abs(diff)

    mse_v  = float(np.mean(sq))
    rmse_v = float(np.sqrt(mse_v))
    mae_v  = float(np.mean(abs_d))

    t64 = true.astype(np.float64)
    p64 = pred.astype(np.float64)
    rse_v = float(
        np.sqrt(np.sum((t64 - p64) ** 2))
        / np.sqrt(np.sum((t64 - t64.mean()) ** 2))
    )

    bias_v = float(np.mean(diff))
    da_v   = float(np.mean(np.sign(pred) == np.sign(true)))

    # Spearman rank-IC across the surface, per (window, step).
    # level   : rank-correlate predicted vs true CHANGES from forecast origin.
    #           Persistence (pred==origin) → constant zero → NaN by design.
    # logdiff : rank-correlate raw values (logdiffs are already changes; the
    #           raw cross-sectional rank IS the direction signal we want).
    if target_space == "level":
        pred_for_ic = pred - origin
        true_for_ic = true - origin
    elif target_space == "logdiff":
        pred_for_ic = pred
        true_for_ic = true
    else:
        raise ValueError(f"Unknown target_space {target_space!r}")

    N, P, F = pred.shape
    ic = np.full((N, P), np.nan)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", ConstantInputWarning)
        for i in range(N):
            for t in range(P):
                r, _ = spearmanr(pred_for_ic[i, t], true_for_ic[i, t])
                ic[i, t] = r if np.isfinite(r) else np.nan

    with warnings.catch_warnings():
        # Persist(ref) → IC array is all-NaN; nanmean warns "Mean of empty slice".
        warnings.simplefilter("ignore", RuntimeWarning)
        ic_mean_v = float(np.nanmean(ic))
        ic_std_v  = float(np.nanstd(ic))
        per_h_ic  = np.nanmean(ic, axis=0)

    per_h_mse = np.mean(sq,    axis=(0, 2))
    per_h_mae = np.mean(abs_d, axis=(0, 2))

    # LSTS — overall (averaged across all windows × horizons × surface cells).
    overall_lsts = _lsts_components(pred.reshape(-1, F), true.reshape(-1, F),
                                    moneyness, tau)

    # Per-horizon LSTS arrays.
    per_h_lsts = {f"lsts_{k}": np.empty(P, dtype=np.float64)
                  for k in ("level", "skew", "term", "curvature")}
    for h in range(P):
        comp = _lsts_components(pred[:, h, :], true[:, h, :], moneyness, tau)
        for k, v in comp.items():
            per_h_lsts[k][h] = v

    out = {
        "mse": mse_v, "rmse": rmse_v, "mae": mae_v, "rse": rse_v,
        "bias": bias_v, "da": da_v,
        "ic_mean": ic_mean_v, "ic_std": ic_std_v,
        "_per_h_mse": per_h_mse,
        "_per_h_mae": per_h_mae,
        "_per_h_ic":  per_h_ic,
    }
    out.update(overall_lsts)
    for k, arr in per_h_lsts.items():
        out[f"_per_h_{k}"] = arr
    return out


# ─── Display ──────────────────────────────────────────────────────────────────

OVERALL_COLS = ["mse", "rmse", "mae", "rse", "bias", "da",
                "ic_mean", "ic_std",
                "lsts_level", "lsts_skew", "lsts_term", "lsts_curvature"]
COL_FMT = {
    "mse": ".6f", "rmse": ".6f", "mae": ".6f", "rse": ".6f",
    "bias": "+.6f", "da": ".4f", "ic_mean": "+.4f", "ic_std": ".4f",
    "lsts_level":     ".4e",
    "lsts_skew":      ".4e",
    "lsts_term":      ".4e",
    "lsts_curvature": ".4e",
}


def _fmt(val: float, cw: int, fmt: str) -> str:
    if fmt.startswith("+"):
        return format(val, f">+{cw}{fmt[1:]}")
    return format(val, f">{cw}{fmt}")


def _col_width(results: list[dict]) -> int:
    return max(14, max(len(r["name"]) for r in results) + 2)


def print_summary(results: list[dict], pred_len: int):
    cw = _col_width(results)
    rw = 14
    names = [r["name"] for r in results]
    horizons = [h for h in REPORT_HORIZONS if h <= pred_len]

    sep   = "=" * (rw + 1 + cw * len(names))
    hdash = "-" * (rw + 1 + cw * len(names))

    print(f"\n{sep}")
    print(f"{'Metric':<{rw}} " + "".join(f"{n:>{cw}}" for n in names))
    print(sep)
    for m in OVERALL_COLS:
        fmt = COL_FMT[m]
        row = f"{m:<{rw}} " + "".join(_fmt(r[m], cw, fmt) for r in results)
        print(row)
    print(sep)

    n_ref = results[0]["n_windows"]
    print(f"\nPer-horizon Spearman IC  (N={n_ref} reference windows):")
    print(f"{'h':<{rw}}" + "".join(f"{n:>{cw}}" for n in names))
    print(hdash)
    for h in horizons:
        idx = h - 1
        row = f"t+{h:<{rw-2}}" + "".join(_fmt(r["_per_h_ic"][idx], cw, "+.4f") for r in results)
        print(row)

    print(f"\nPer-horizon MSE:")
    print(f"{'h':<{rw}}" + "".join(f"{n:>{cw}}" for n in names))
    print(hdash)
    for h in horizons:
        idx = h - 1
        row = f"t+{h:<{rw-2}}" + "".join(_fmt(r["_per_h_mse"][idx], cw, ".6f") for r in results)
        print(row)

    for comp in ("level", "skew", "term", "curvature"):
        key = f"_per_h_lsts_{comp}"
        print(f"\nPer-horizon LSTS {comp}:")
        print(f"{'h':<{rw}}" + "".join(f"{n:>{cw}}" for n in names))
        print(hdash)
        for h in horizons:
            idx = h - 1
            row = f"t+{h:<{rw-2}}" + "".join(_fmt(r[key][idx], cw, ".4e") for r in results)
            print(row)
    print()


# ─── Save ─────────────────────────────────────────────────────────────────────

def save_results(results: list[dict], out_dir: str, dataset: str,
                 target_space: str, seq_len: int, pred_len: int):
    os.makedirs(out_dir, exist_ok=True)
    ts  = datetime.now().strftime("%Y%m%d_%H%M%S")
    tag = f"{dataset}_{target_space}_sl{seq_len}_pl{pred_len}"

    scalar_rows = [
        {k: v for k, v in r.items() if not k.startswith("_")}
        for r in results
    ]
    df_overall = pd.DataFrame(scalar_rows)
    df_overall.to_csv(os.path.join(out_dir, f"{tag}_{ts}.csv"), index=False)
    df_overall.to_csv(os.path.join(out_dir, f"latest_{tag}.csv"), index=False)

    h_rows = []
    for r in results:
        for h in range(1, pred_len + 1):
            h_rows.append({
                "model":           r["name"],
                "horizon":         h,
                "ic":              r["_per_h_ic"][h - 1],
                "mse":             r["_per_h_mse"][h - 1],
                "mae":             r["_per_h_mae"][h - 1],
                "lsts_level":      r["_per_h_lsts_level"][h - 1],
                "lsts_skew":       r["_per_h_lsts_skew"][h - 1],
                "lsts_term":       r["_per_h_lsts_term"][h - 1],
                "lsts_curvature":  r["_per_h_lsts_curvature"][h - 1],
            })
    pd.DataFrame(h_rows).to_csv(
        os.path.join(out_dir, f"latest_horizons_{tag}.csv"), index=False)

    summary = {
        "timestamp":    ts,
        "dataset":      dataset,
        "target_space": target_space,
        "seq_len":      seq_len,
        "pred_len":     pred_len,
        "models": {
            r["name"]: {k: v for k, v in r.items() if not k.startswith("_")}
            for r in results
        },
    }
    with open(os.path.join(out_dir, f"latest_summary_{tag}.json"), "w") as f:
        json.dump(summary, f, indent=2)

    print(f"Saved to {out_dir}/  (tagged {tag})")


