def _config_n_iv_matches(cfg_path: str, expected_n_iv: int | None) -> bool:
    """If expected_n_iv is given, only accept dirs whose config.json `n_iv`
    matches the current CSV. Lets stale tuning dirs from a different grid
    (e.g. previous 20x20=400) be skipped automatically."""
    if expected_n_iv is None:
        return True
    try:
        with open(cfg_path) as f:
            cfg = json.load(f)
    except Exception:
        return False
    return int(cfg.get("n_iv", -1)) == int(expected_n_iv)


def _resolve_best_combo(tuning_dir: str, name: str,
                        expected_n_iv: int | None = None) -> str | None:
    """
    Read `<tuning_dir>/leaderboard.csv` and pick the lowest-val_loss combo
    that has both config.json and best_model.pt (and matches expected_n_iv
    when provided).
    """
    lb_path = os.path.join(tuning_dir, "leaderboard.csv")
    if not os.path.exists(lb_path):
        return None
    df = pd.read_csv(lb_path)
    if "best_val_loss" not in df.columns or "combo_id" not in df.columns:
        print(f"  {name}: leaderboard at {lb_path} missing required columns")
        return None
    df = df.dropna(subset=["best_val_loss"]).sort_values("best_val_loss")
    skipped_shape = 0
    for _, row in df.iterrows():
        cid = row["combo_id"]
        d = os.path.join(tuning_dir, cid)
        cfg  = os.path.join(d, "config.json")
        ckpt = os.path.join(d, "best_model.pt")
        if not (os.path.exists(cfg) and os.path.exists(ckpt)):
            continue
        if not _config_n_iv_matches(cfg, expected_n_iv):
            skipped_shape += 1
            continue
        print(f"  {name}: tuning best = {cid} "
              f"(val_loss={row['best_val_loss']:.6f}) at {d}")
        return d
    if skipped_shape:
        print(f"  {name}: {skipped_shape} combo(s) under {tuning_dir} "
              f"skipped (n_iv != {expected_n_iv}); will try result_dir")
    else:
        print(f"  {name}: no combo under {tuning_dir} has both config.json and best_model.pt")
    return None


def _resolve_result_dir(result_glob: str, requires_ckpt: bool, name: str,
                        expected_n_iv: int | None = None) -> str | None:
    """Glob `result_glob` and return the most-recently-modified dir that has
    config.json (and best_model.pt when `requires_ckpt`), filtered by
    expected_n_iv when provided. VAR has no checkpoint — refits from
    CSV+config in seconds."""
    matches = glob.glob(result_glob)
    if not matches:
        return None
    candidates = []
    for d in matches:
        cfg  = os.path.join(d, "config.json")
        ckpt = os.path.join(d, "best_model.pt")
        if not (os.path.exists(cfg) and (not requires_ckpt or os.path.exists(ckpt))):
            continue
        if not _config_n_iv_matches(cfg, expected_n_iv):
            continue
        candidates.append((d, os.path.getmtime(cfg)))
    if not candidates:
        return None
    d = max(candidates, key=lambda t: t[1])[0]
    print(f"  {name}: result dir = {d}")
    return d


def _is_var(spec: dict) -> bool:
    return "VAR/" in spec.get("regen_script", "")


def _maybe_regen(spec: dict, name: str, infer_batch: int,
                 expected_n_iv: int | None = None) -> str | None:
    out_dir = None
    if spec.get("tuning_dir"):
        out_dir = _resolve_best_combo(spec["tuning_dir"], name, expected_n_iv)
    if out_dir is None and spec.get("result_dir"):
        out_dir = _resolve_result_dir(spec["result_dir"],
                                      requires_ckpt=not _is_var(spec),
                                      name=name,
                                      expected_n_iv=expected_n_iv)
    if out_dir is None:
        return None

    pred_path = os.path.join(out_dir, "pred.npy")
    if os.path.exists(pred_path):
        print(f"  {name}: using existing pred.npy at {out_dir}")
        return pred_path

    cmd = [sys.executable, spec["regen_script"],
           "--predict_only", "--out_dir", out_dir]
    if not _is_var(spec):
        cmd.extend(["--batch_size", str(infer_batch)])
    print(f"  {name}: pred.npy missing → regenerating from {out_dir} ...")
    rc = subprocess.run(cmd).returncode
    if rc != 0 or not os.path.exists(pred_path):
        print(f"  {name}: regeneration failed (exit {rc})")
        return None
    print(f"  {name}: regenerated pred.npy")
    return pred_path


# ─── Main ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="Compare SPX IV forecasting models")
    parser.add_argument("--csv_path", default="SPX_surfaces.csv")
    parser.add_argument("--dataset",  default=DEFAULT_DATASET, choices=DATASET_CHOICES)
    parser.add_argument("--target_space", default=DEFAULT_TARGET_SPACE,
                        choices=TARGET_SPACE_CHOICES)
    parser.add_argument("--seq_len",  type=int, default=DEFAULT_SEQ_LEN)
    parser.add_argument("--pred_len", type=int, default=DEFAULT_PRED_LEN)
    parser.add_argument("--infer_batch", type=int, default=DEFAULT_INFER_BATCH,
                        help="Inference batch size when regenerating pred.npy. "
                             "Defaults to 32 (local-friendly), independent of "
                             "the (possibly larger) training batch.")
    parser.add_argument("--out_dir",  default="comparison_results")
    parser.add_argument("--models",   nargs="*", default=None,
                        help="Filter by case-insensitive name prefix "
                             "(e.g. --models DLinear HOT). Default: all.")
    args = parser.parse_args()

    models_for_run = build_models(args.dataset, args.target_space,
                                  args.seq_len, args.pred_len)
    if args.models:
        keep = [m.lower() for m in args.models]
        models_for_run = [
            spec for spec in models_for_run
            if any(spec["name"].lower().startswith(k) for k in keep)
        ]
        kept_names = [s["name"] for s in models_for_run]
        print(f"Model filter --models {args.models} → {kept_names}")
        if not models_for_run:
            print("No models match the filter; nothing to do.")
            return

    print(f"Building reference ground truth "
          f"(dataset={args.dataset}, target_space={args.target_space}, "
          f"seq_len={args.seq_len}, pred_len={args.pred_len})...")
    trues, persist, ref_dates, meta = build_reference(
        args.csv_path, dataset=args.dataset, target_space=args.target_space,
        seq_len=args.seq_len, pred_len=args.pred_len,
    )
    n_iv = meta["n_iv"]
    moneyness, tau = meta["moneyness"], meta["tau"]
    print(f"  T={meta['T']}, n_iv={n_iv}  "
          f"({meta['n_moneyness']} moneyness × {meta['n_tau']} tau), "
          f"train ends {meta['train_end_date']}")
    print(f"  test windows={meta['n_test']}, {meta['date_range']}")
    print(f"  inference batch (regen only): {args.infer_batch}")

    results = []

    m = compute_metrics(persist, trues, moneyness, tau,
                        origin=persist, target_space=args.target_space)
    m["name"] = "Persist(ref)"
    m["n_windows"] = meta["n_test"]
    m["source"] = "built-in"
    results.append(m)
    print(f"  Persist(ref): OK ({meta['n_test']} windows)")

    for spec in models_for_run:
        name = spec["name"]
        pred_path = _maybe_regen(spec, name, args.infer_batch,
                                 expected_n_iv=n_iv)
        if pred_path is None:
            print(f"  {name}: no regen-eligible dir for dataset={args.dataset!r}, "
                  f"target_space={args.target_space!r} — skipping")
            continue

        sibling_dates = os.path.join(os.path.dirname(pred_path), "start_dates.npy")
        dates_path = sibling_dates if os.path.exists(sibling_dates) else None

        try:
            pred = LOADERS[spec["loader"]](pred_path, n_iv)
        except Exception as e:
            print(f"  {name}: load error — {e}")
            continue

        if dates_path is not None:
            pred_dates = np.load(dates_path).astype("datetime64[D]")
            try:
                pred = align_to_ref(pred, pred_dates, ref_dates, name)
            except ValueError as e:
                print(f"  {name}: date alignment failed — {e}")
                continue
            n_windows = len(ref_dates)
            true_aligned    = trues
            persist_aligned = persist
        else:
            n_windows = min(len(pred), len(trues))
            if n_windows < len(trues):
                print(
                    f"  {name}: WARNING — no start_dates.npy; assuming sequential "
                    f"alignment from window 0 (model has {len(pred)}, ref has {len(trues)})."
                )
            pred = pred[:n_windows]
            true_aligned    = trues[:n_windows]
            persist_aligned = persist[:n_windows]

        if pred.shape[1:] != (args.pred_len, n_iv):
            print(f"  {name}: unexpected pred shape {pred.shape} — skipping")
            continue

        m = compute_metrics(pred, true_aligned, moneyness, tau,
                            origin=persist_aligned,
                            target_space=args.target_space)
        m["name"] = name
        m["n_windows"] = n_windows
        m["source"] = pred_path
        results.append(m)
        write_per_model_metrics(os.path.dirname(pred_path), name, args.dataset,
                                args.target_space, args.seq_len, args.pred_len, m)
        print(f"  {name}: OK ({n_windows} windows, {pred_path})")

    if len(results) == 1:
        print("\nOnly baseline available — nothing to compare.")
        return

    print_summary(results, args.pred_len)
    save_results(results, args.out_dir, args.dataset, args.target_space,
                 args.seq_len, args.pred_len)


if __name__ == "__main__":
    main()
